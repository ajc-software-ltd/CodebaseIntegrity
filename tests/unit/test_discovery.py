"""Tests for project file discovery."""

from pathlib import Path

import pytest

from cii.core.configuration import CiiConfig
from cii.scanner.discovery import discover
from cii.scanner.file_filter import FileFilter


def _filter() -> FileFilter:
    config = CiiConfig.defaults()
    return FileFilter(config.scan, config.languages)


def _write(path: Path, content: str = "x = 1\n") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


class TestDiscover:
    def test_respects_exclusions(self, project_root: Path) -> None:
        _write(project_root / "src" / "a.py")
        _write(project_root / "node_modules" / "b.py")
        _write(project_root / "sub" / "node_modules" / "d.py")
        _write(project_root / "build" / "c.py")
        records, stats = discover(project_root, _filter())
        assert [record.relative_path for record in records] == ["src/a.py"]
        assert stats.discovered == 1
        assert stats.excluded_directories == 3

    def test_skips_unsupported_binary_and_large(self, project_root: Path) -> None:
        _write(project_root / "a.py")
        _write(project_root / "image.png")
        (project_root / "binary.py").write_bytes(b"\x00ab")  # under the size limit
        _write(project_root / "big.py", "x = 11111111\n")  # over the size limit
        config = CiiConfig.defaults()
        config.scan.max_file_size_bytes = 8
        records, stats = discover(project_root, FileFilter(config.scan, config.languages))
        assert [record.relative_path for record in records] == ["a.py"]
        assert stats.unsupported_extension == 1
        assert stats.binary == 1
        assert stats.too_large == 1

    def test_skips_generated_files(self, project_root: Path) -> None:
        _write(project_root / "a.py")
        _write(project_root / "gen.py", "# Auto-generated by tool. Do not edit.\n")
        records, stats = discover(project_root, _filter())
        assert [record.relative_path for record in records] == ["a.py"]
        assert stats.generated == 1

    def test_symlinks_skipped_by_default(self, project_root: Path, tmp_path: Path) -> None:
        _write(project_root / "a.py")
        outside = tmp_path / "outside.py"
        _write(outside)
        (project_root / "link.py").symlink_to(outside)
        (project_root / "linkdir").symlink_to(project_root / "sub", target_is_directory=True)
        _write(project_root / "sub" / "b.py")
        records, stats = discover(project_root, _filter())
        assert [record.relative_path for record in records] == ["a.py", "sub/b.py"]
        assert stats.symlink_skipped == 2

    def test_symlinked_files_followed_when_enabled(self, project_root: Path) -> None:
        _write(project_root / "real" / "a.py")
        (project_root / "linkdir").symlink_to(
            project_root / "real", target_is_directory=True
        )
        records, _ = discover(project_root, _filter(), follow_symlinks=True)
        assert [record.relative_path for record in records] == [
            "linkdir/a.py",
            "real/a.py",
        ]

    def test_symlink_escaping_root_never_followed(self, project_root: Path, tmp_path: Path) -> None:
        outside = tmp_path / "outside"
        _write(outside / "secret.py")
        (project_root / "linkdir").symlink_to(outside, target_is_directory=True)
        records, stats = discover(project_root, _filter(), follow_symlinks=True)
        assert records == []
        assert stats.symlink_skipped == 1

    def test_symlink_cycle_terminates(self, project_root: Path) -> None:
        _write(project_root / "sub" / "a.py")
        (project_root / "sub" / "loop").symlink_to(project_root, target_is_directory=True)
        records, _ = discover(project_root, _filter(), follow_symlinks=True)
        assert [record.relative_path for record in records] == ["sub/a.py"]

    def test_records_carry_metadata(self, project_root: Path) -> None:
        path = project_root / "pkg" / "a.py"
        _write(path)
        records, _ = discover(project_root, _filter())
        record = records[0]
        assert record.filename == "a.py"
        assert record.extension == ".py"
        assert record.language.value == "python"
        assert record.file_size == path.stat().st_size
        assert record.modified_at == pytest.approx(path.stat().st_mtime)
        assert record.content_hash is None
