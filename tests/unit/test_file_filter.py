"""Tests for file eligibility filtering."""

from pathlib import Path

import pytest

from cii.core.configuration import CiiConfig
from cii.core.enums import Language
from cii.scanner.file_filter import FileFilter


@pytest.fixture
def file_filter() -> FileFilter:
    config = CiiConfig.defaults()
    return FileFilter(config.scan, config.languages)


class TestExclusion:
    def test_excluded_by_component(self, file_filter: FileFilter) -> None:
        assert file_filter.is_excluded_directory("node_modules")
        assert file_filter.is_excluded_directory("src/node_modules/pkg")
        assert file_filter.is_excluded_directory(".git")
        assert not file_filter.is_excluded_directory("src")

    def test_inclusion_overrides_exclusion(self) -> None:
        config = CiiConfig.defaults()
        config.scan.included_directories = ["generated"]
        file_filter = FileFilter(config.scan, config.languages)
        assert not file_filter.is_excluded_directory("generated")
        assert not file_filter.is_excluded_directory("generated/deep")
        assert file_filter.is_excluded_directory("vendor")


class TestClassify:
    @pytest.mark.parametrize(
        ("name", "language"),
        [
            ("a.c", Language.C),
            ("a.cpp", Language.CPP),
            ("a.HPP", Language.CPP),  # case-insensitive
            ("a.cs", Language.CSHARP),
            ("a.py", Language.PYTHON),
        ],
    )
    def test_supported(self, file_filter: FileFilter, name: str, language: Language) -> None:
        assert file_filter.classify(Path(name)) == language

    def test_unsupported(self, file_filter: FileFilter) -> None:
        assert file_filter.classify(Path("image.png")) is None
        assert file_filter.classify(Path("Makefile")) is None


class TestContentChecks:
    def test_too_large(self, file_filter: FileFilter) -> None:
        assert file_filter.is_too_large(1) is False
        assert file_filter.is_too_large(2_097_152) is False
        assert file_filter.is_too_large(2_097_153) is True

    def test_binary_detection(self, file_filter: FileFilter, tmp_path: Path) -> None:
        binary = tmp_path / "binary.bin"
        binary.write_bytes(b"abc\x00def")
        text = tmp_path / "text.py"
        text.write_text("print('hello')\n")
        assert file_filter.is_binary(binary) is True
        assert file_filter.is_binary(text) is False

    def test_generated_detection(self, file_filter: FileFilter, tmp_path: Path) -> None:
        generated = tmp_path / "generated.py"
        generated.write_text("# Auto-generated by codegen. Do not edit.\nx = 1\n")
        plain = tmp_path / "plain.py"
        plain.write_text("# generated utilities\nx = 1\n")  # not a marker
        assert file_filter.is_generated(generated) is True
        assert file_filter.is_generated(plain) is False

    def test_generated_detection_disabled(self, tmp_path: Path) -> None:
        config = CiiConfig.defaults()
        config.scan.detect_generated_files = False
        file_filter = FileFilter(config.scan, config.languages)
        generated = tmp_path / "generated.py"
        generated.write_text("# @generated\nx = 1\n")
        assert file_filter.is_generated(generated) is False
